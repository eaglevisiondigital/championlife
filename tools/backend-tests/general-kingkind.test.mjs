import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
const read=p=>readFileSync(path.join(root,p),'utf8');
const sql=read('supabase/migrations/20261029235955_general_king_kind_resource_registration.sql');
const page=read('king-kind-signup.html');
const ui=read('assets/js/general-king-kind-signup.js');
const manifest=JSON.parse(read('tools/site-build/public-files.json'));
let tests=0;
const check=(condition,message)=>{assert.ok(condition,message);tests++;};
check(sql.includes('public.general_king_kind_registrants'), 'separate resource registry');
check(sql.includes('enable row level security'), 'RLS enabled');
check(/revoke all on public\.general_king_kind_registrants from public, anon, authenticated/i.test(sql), 'no direct PII grants');
check(/u\.email_confirmed_at is not null/.test(sql), 'verified email required');
check(sql.includes('subject uuid := auth.uid()'), 'derived user identity');
check(!/outreach_registrations\s*\(/.test(sql), 'no new outreach decision writes');
check(!/insert into public\.outreach_registrations/i.test(sql), 'no outreach enrollment');
check(sql.includes('king_kind_registered_outreach_read'), 'preserves exact storage policy');
check(sql.includes("r.source in ('bessemer_al_2026', 'huntsville_al_2026')"), 'preserves previous eligible audiences');
check(sql.includes('and g.verified_email=lower(btrim(u.email))'), 'account email change fails closed');
check(sql.includes('join public.general_king_kind_registrants'), 'resource registration required for book');
check(page.includes('discipleship-login.html?next=%2Fking-kind-signup.html'), 'existing email auth handoff');
check(page.includes('king-kind-reader.html'), 'private reader retained');
check(page.includes('my-discipleship.html'), 'existing course dashboard retained');
check(!/government (photo )?ID/i.test(page), 'no government ID collection');
check(ui.includes('auth.client.auth.getUser'), 'session confirmed via provider');
check(ui.includes("register_general_king_kind_resource"), 'RPC call wired');
check(ui.includes("currentUserId!==requestedUser"), 'account-change guard');
check(!/signInWithOtp\(/.test(ui), 'reuses existing login rather than duplicate auth callback');
check(manifest.includes('king-kind-signup.html') && manifest.includes('assets/js/general-king-kind-signup.js'), 'both assets in public allowlist');
console.log('general King Kind source-contract checks:',tests,'passed (static only; native RLS and browser acceptance still required)');
